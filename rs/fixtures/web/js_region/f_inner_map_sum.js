function region(inputs, uniforms, outputs, start, stop) {
  const fail = (code, message) => { const e = new Error(message); e.code = code; throw e; };
  const wrap = x => BigInt.asIntN(63, x);
  const convert = (name, x) => Number.isFinite(x) && Math.abs(x) < 4e18 ? BigInt(Math.trunc(x)) : fail('E_NONFINITE', name + ' produced a nonfinite value.');
  const divide = (a, b, mod) => b === 0n ? fail('E_RANGE', 'Integer division by zero.') : wrap(mod ? a % b : a / b);
  const shift = (a, b, right) => b < 0n || b > 62n ? fail('E_RANGE', 'Integer shift count must be within [0, 62].') : wrap(right ? BigInt.asUintN(63, a) >> b : a << b);
  const in0 = inputs[0];
  const out0 = outputs[0];
  for (let i = start; i < stop; i++) {
    const o = i;
    const j0 = i;
    let r0;
    r0 = in0[j0];
    let r1;
    r1 = 0n;
    let r2;
    r2 = Number(r0);
    if (!Number.isFinite(r2)) return 1;
    let r3;
    r3 = 0;
    let r4;
    r4 = r2 + r3;
    if (!Number.isFinite(r4)) return 1;
    let r5;
    r5 = convert("+", Math.floor(r4 + 0.5));
    let r6;
    r6 = 1n;
    let r7;
    r7 = 1;
    let r8;
    r8 = r2 + r7;
    if (!Number.isFinite(r8)) return 1;
    let r9;
    r9 = convert("+", Math.floor(r8 + 0.5));
    let r10;
    r10 = 2n;
    let r11;
    r11 = 2;
    let r12;
    r12 = r2 + r11;
    if (!Number.isFinite(r12)) return 1;
    let r13;
    r13 = convert("+", Math.floor(r12 + 0.5));
    let r14;
    r14 = wrap(r1 + r5);
    let r15;
    r15 = wrap(r14 + r9);
    let r16;
    r16 = wrap(r15 + r13);
    let r17;
    r17 = uniforms[0][17];
    let r18;
    r18 = Number(r16);
    if (!Number.isFinite(r18)) return 1;
    let r19;
    r19 = Number(r17);
    if (!Number.isFinite(r19)) return 1;
    let r20;
    r20 = r18 + r19;
    if (!Number.isFinite(r20)) return 1;
    let r21;
    r21 = convert("+", Math.floor(r20 + 0.5));
    out0[o * 1 + 0] = r21;
  }
  return 0;
}
