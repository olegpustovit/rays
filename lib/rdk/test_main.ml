let () =
  match Array.to_list Sys.argv with
  | [_; selection] ->
      let selected = List.filter
          (fun (group, name, _) -> selection = group || selection = name) tests in
      if selected = [] then failwith ("unknown test group or test: " ^ selection);
      List.iter (fun (_, name, run) ->
        Printf.eprintf "%s\n%!" name;
        run ()) selected
  | _ -> failwith "usage: test_main <group|test_name>"
